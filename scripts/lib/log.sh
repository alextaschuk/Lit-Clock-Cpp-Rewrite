#!/bin/bash
##################################################
# Functions for basic logging.
#
# This is source'd into common.sh for all other
# scripts to use.
##################################################


##################################################
# Log a message to stdout with a timestamp.
#
# Timestamp has format of "YYYY-MM-DD HH:MM:SS"
##################################################
log() { printf '%s: %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*"; }

##################################################
# Log an info message.
##################################################
info() { log "INFO: $*"; }

##################################################
# Log an error message to stderr.
##################################################
error() { echo "Error: $*" >&2; }

##################################################
# Log an error message to stderr with a timestamp.
##################################################
error_ts() { log "ERROR: $*" >&2; }

##################################################
# Log a debug message to stderr.
##################################################
debug() { log "DEBUG: $*" >&2; }

##################################################
# Log a warning message to stderr.
##################################################
warn() { log "WARN: $*" >&2; }

##################################################
# Log a fatal message to stderr.
##################################################
fatal() { log "FATAL: $*" >&2; }
